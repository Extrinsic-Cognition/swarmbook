/**
 * The mint at this instant (ms): 'unset' (no launch day: the seats sell and nothing counts down), 'before' (the launch day ahead), 'open'
 * (within its MINT_DAYS: daysLeft, the last day counting 1) or 'closed' (after them: a seat pressed reads closed). freeAt: the day the code is
 * everyone's, OPEN_DAYS from the launch (the code's drop taken to land on the launch day); free: that day has come. The wall stands exactly
 * while the mint is not closed (exclusive() above).
 */
export function mintState(now, launch = LAUNCH_DAY, closes = null) {
  const start = launchMs(launch), close = closesMs(closes);
  // a close given (THE FREEZE ON THE DRAWN ARROW): the mint is open until it, whatever the launch day says
  if (close !== null) {
    const freeAt = start === null ? null : start + OPEN_DAYS * DAY_MS, free = freeAt !== null && now >= freeAt;
    return now >= close ? {phase: 'closed', start, end: close, daysLeft: 0, freeAt, free, closes: true}
      : {phase: 'open', start, end: close, daysLeft: Math.ceil((close - now) / DAY_MS), freeAt, free, closes: true};
  }
  if (start === null) return {phase: 'unset', start: null, end: null, daysLeft: null, freeAt: null, free: false};
  const end = start + MINT_DAYS * DAY_MS, freeAt = start + OPEN_DAYS * DAY_MS, free = now >= freeAt;
  if (!(now >= start)) return {phase: 'before', start, end, daysLeft: MINT_DAYS, freeAt, free};
  if (!(now >= end)) return {phase: 'open', start, end, daysLeft: Math.ceil((end - now) / DAY_MS), freeAt, free};
  return {phase: 'closed', start, end, daysLeft: 0, freeAt, free};
}
