/**
 * A piece docking as a world of the twelve does: along the orbits' spherical Lissajous (3:2: [sin 2u cos 3u, cos 2u, sin 2u sin 3u], on
 * lane `lane`'s tilt) from curve parameter `from` over `span`, what is left of the way shrinking (1 - smoothstep) to its place, its size
 * from `small` to whole, its light in over the first `light` of the time. reach: px of the way at the start. steps + 1 keyframes {offset,
 * x, y, scale, opacity}: the last one is the place itself.
 */
export function dock(lane = 0, {from = 0, span = Math.PI / 2, reach = 120, steps = 24, small = 0.35, light = 0.45} = {}) {
  const tilt = TILTS[((lane % 4) + 4) % 4], c = Math.cos(tilt), s = Math.sin(tilt), out = [];
  for (let i = 0; i <= steps; i++) {
    const k = i / steps, u = from + span * k, polar = Math.sin(2 * u), left = reach * (1 - smooth(k));
    const x = polar * Math.cos(3 * u), y = Math.cos(2 * u) * c - polar * Math.sin(3 * u) * s;
    out.push({offset: k, x: Math.round(left * x * 100) / 100 || 0, y: Math.round(-left * y * 100) / 100 || 0,
      scale: Math.round((small + (1 - small) * smooth(k)) * 1000) / 1000, opacity: Math.round(smooth(k / light) * 1000) / 1000});
  }
  return out;
}

